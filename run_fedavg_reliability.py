# SAVE
# ============================================================

def save_results(
    history,
    scenario,
    args,
):

    output_dir = (
        OUTPUT_ROOT
        / scenario
    )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    history.to_csv(
        output_dir
        / "fedavg_reliability_round_history.csv",
        index=False,
    )

    final = history.iloc[-1]

    total_communication = (
        history[
            "total_communication_bytes"
        ].sum()
    )

    final_metrics = pd.DataFrame(
        {
            "metric": [
                "scenario",
                "rounds",
                "clients",
                "local_epochs",
                "batch_size",
                "learning_rate",
                "seed",
                "final_accuracy",
                "final_precision",
                "final_recall",
                "final_f1",
                "final_roc_auc",
                "final_test_loss",
                "total_communication_bytes",
                "total_communication_mib",
                "total_round_time_seconds",
            ],
            "value": [
                scenario,
                args.rounds,
                N_CLIENTS,
                args.local_epochs,
                args.batch_size,
                args.learning_rate,
                args.seed,
                final["accuracy"],
                final["precision"],
                final["recall"],
                final["f1"],
                final["roc_auc"],
                final["global_test_loss"],
                total_communication,
                total_communication
                / (1024 ** 2),
                history[
                    "round_time_seconds"
                ].sum(),
            ],
        }
    )

    final_metrics.to_csv(
        output_dir
        / "fedavg_reliability_final_metrics.csv",
        index=False,
    )

    config = pd.DataFrame(
        {
            "parameter": [
                "scenario",
                "clients",
                "rounds",
                "local_epochs",
                "batch_size",
                "learning_rate",
                "seed",
                "device",
                "model",
                "input_features",
                "hidden_layers",
                "dropout",
                "aggregation",
            ],
            "value": [
                scenario,
                N_CLIENTS,
                args.rounds,
                args.local_epochs,
                args.batch_size,
                args.learning_rate,
                args.seed,
                str(DEVICE),
                "FederatedMLP",
                36,
                "128-64-32",
                0.40,
                "FedAvg",
            ],
        }
    )

    config.to_csv(
        output_dir
        / "fedavg_reliability_config.csv",
        index=False,
    )

    return output_dir


