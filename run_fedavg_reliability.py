def load_clients():
    clients = {}

    for client_id in range(1, N_CLIENTS + 1):

        path = (
            CLIENT_DIR
            / f"client_{client_id:02d}.csv"
        )

        if not path.exists():
            raise FileNotFoundError(
                f"Missing client file:\n"
                f"{path.resolve()}"
            )

        clients[client_id] = pd.read_csv(path)

    return clients


def load_global_test():
    if not GLOBAL_TEST_FILE.exists():
        raise FileNotFoundError(
            f"Missing global test file:\n"
            f"{GLOBAL_TEST_FILE.resolve()}"
        )

    return pd.read_csv(
        GLOBAL_TEST_FILE
    )


def load_reliability_schedule(
    scenario: str,
    rounds: int,
):
    path = (
        RELIABILITY_ROOT
        / scenario
        / "reliability_schedule.csv"
    )

    if not path.exists():
        raise FileNotFoundError(
            f"Missing reliability schedule:\n"
            f"{path.resolve()}\n"
            "Run simulate_industrial_client_reliability.py first."
        )

    schedule = pd.read_csv(path)

    required = {
        "round",
        "client_id",
        "available",
        "sensor_noise_multiplier",
        "stale_update",
        "staleness_rounds",
        "reliability_score",
    }

    missing = required - set(
        schedule.columns
    )

    if missing:
        raise ValueError(
            f"Schedule is missing columns: {sorted(missing)}"
        )

    schedule["round"] = (
        schedule["round"].astype(int)
    )
    schedule["client_id"] = (
        schedule["client_id"].astype(int)
    )
    schedule["available"] = (
        schedule["available"].astype(bool)
    )
    schedule["sensor_noise_multiplier"] = (
        schedule["sensor_noise_multiplier"].astype(float)
    )
    schedule["stale_update"] = (
        schedule["stale_update"].astype(bool)
    )
    schedule["staleness_rounds"] = (
        schedule["staleness_rounds"].astype(int)
    )
    schedule["reliability_score"] = (
        schedule["reliability_score"].astype(float)
    )

    schedule = schedule[
        schedule["round"] <= rounds
    ].copy()

    expected_rows = rounds * N_CLIENTS

    if len(schedule) != expected_rows:
        raise ValueError(
            f"Expected {expected_rows} schedule rows, "
            f"got {len(schedule)}."
        )

    return schedule.sort_values(
        ["round", "client_id"]
    ).reset_index(drop=True)


# ============================================================
# SCALING
# ============================================================

def prepare_data(
    clients,
    global_test,
):
    train_pool = pd.concat(
        list(clients.values()),
        ignore_index=True,
    )

    feature_columns = get_feature_columns(
        train_pool
    )

    scaler = StandardScaler()

    scaler.fit(
        train_pool[
            feature_columns
        ]
    )

    scaled_clients = {}

    for client_id, df in clients.items():
        scaled = df.copy()

        scaled[
            feature_columns
        ] = scaler.transform(
            df[
                feature_columns
            ]
        )

        scaled_clients[
            client_id
        ] = scaled

    scaled_test = global_test.copy()

    scaled_test[
        feature_columns
    ] = scaler.transform(
        global_test[
            feature_columns
        ]
    )

    return (
        scaled_clients,
        scaled_test,
        feature_columns,
    )


# ============================================================
# SENSOR NOISE
# ============================================================

def apply_sensor_noise(
    client_df: pd.DataFrame,
    feature_columns,
    noise_multiplier: float,
    seed: int,
):
    """
    Apply zero-mean Gaussian noise to a temporary local copy.

    Noise std for feature j:
        multiplier * std(feature_j)

    The client dataset saved on disk is never modified.
    """

    if noise_multiplier <= 0:
        return client_df

    rng = np.random.default_rng(
        seed
    )

    noisy = client_df.copy()

    values = noisy[
        feature_columns
    ].to_numpy(
        dtype=np.float32
    )

    feature_std = np.std(
        values,
        axis=0,
        ddof=0,
    )

    noise = rng.normal(
        loc=0.0,
        scale=noise_multiplier * (
            feature_std + 1e-12
        ),
        size=values.shape,
    ).astype(np.float32)

    noisy[
        feature_columns
    ] = values + noise

    return noisy


# ============================================================
# EVALUATION
# ============================================================

def evaluate_model(
    model,
    test_df,
    feature_columns,
):
    model.eval()

    X = torch.tensor(
        test_df[
            feature_columns
        ].to_numpy(
            dtype=np.float32
        ),
        dtype=torch.float32,
        device=DEVICE,
    )

    y = test_df[
        "label"
    ].to_numpy(
        dtype=np.int64
    )

    y_tensor = torch.tensor(
        y,
        dtype=torch.long,
        device=DEVICE,
    )

    criterion = torch.nn.CrossEntropyLoss()

    with torch.no_grad():
        logits = model(X)

        loss = criterion(
            logits,
            y_tensor,
        )

        probabilities = torch.softmax(
            logits,
            dim=1,
        )[:, 1]

        predictions = (
            probabilities >= 0.5
        ).long()

    y_pred = (
        predictions
        .cpu()
        .numpy()
    )

    y_prob = (
        probabilities
        .cpu()
        .numpy()
    )

    return {
        "global_test_loss": float(
            loss.item()
        ),
        "accuracy": float(
            accuracy_score(
                y,
                y_pred,
            )
        ),
        "precision": float(
            precision_score(
                y,
                y_pred,
                zero_division=0,
            )
        ),
        "recall": float(
            recall_score(
                y,
                y_pred,
                zero_division=0,
            )
        ),
        "f1": float(
            f1_score(
                y,
                y_pred,
                zero_division=0,
            )
        ),
        "roc_auc": float(
            roc_auc_score(
                y,
                y_prob,
            )
        ),
    }


# ============================================================
# STALE STATE MANAGEMENT
# ============================================================

def copy_state_dict(
    state,
):
    return OrderedDict(
        (
            name,
            tensor.detach().cpu().clone(),
        )
        for name, tensor in state.items()
    )


# ============================================================
# EXPERIMENT
# ============================================================

def run_experiment(
    scenario: str,
    rounds: int,
    local_epochs: int,
    batch_size: int,
    learning_rate: float,
    seed: int,
):
    set_seed(seed)

    clients = load_clients()
    global_test = load_global_test()

    schedule = load_reliability_schedule(
        scenario,
        rounds,
    )

    (
        scaled_clients,
        scaled_test,
        feature_columns,
    ) = prepare_data(
        clients,
        global_test,
    )

    model = build_model(
        input_size=len(feature_columns)
    ).to(DEVICE)

    global_state = copy_state_dict(
        model.state_dict()
    )

    model_bytes = model_size_bytes(
        global_state
    )

    # Stores the most recent usable local model state
    # for each client. This is used ONLY for the stale-update
    # stress test and is not an adaptive aggregation mechanism.
    previous_client_states = {}

    history = []

    print("=" * 78)
    print("FEDAVG INDUSTRIAL RELIABILITY EXPERIMENT")
    print("=" * 78)

    print(
        f"Scenario          : {scenario}"
    )

    print(
        f"Clients           : {N_CLIENTS}"
    )

    print(
        f"Rounds            : {rounds}"
    )

    print(
        f"Local epochs      : {local_epochs}"
    )

    print(
        f"Batch size        : {batch_size}"
    )

    print(
        f"Learning rate     : {learning_rate}"
    )

    print(
        f"Device            : {DEVICE}"
    )

    print(
        f"Model size        : {model_bytes} bytes"
    )

    for round_number in range(
        1,
        rounds + 1,
    ):

        round_start = time.perf_counter()

        round_schedule = schedule[
            schedule["round"] == round_number
        ]

        available_rows = round_schedule[
            round_schedule["available"]
        ]

        participating_ids = [
            int(x)
            for x in available_rows[
                "client_id"
            ].tolist()
        ]

        if not participating_ids:
            raise RuntimeError(
                f"No available clients in round {round_number}."
            )

        local_states = []
        local_counts = []
        local_losses = []

        actual_noisy_clients = 0
        actual_stale_clients = 0

        print()
        print("-" * 78)
        print(
            f"ROUND {round_number}/{rounds}"
        )

        print(
            "Available clients:",
            participating_ids,
        )

        # ----------------------------------------------------
        # Local training
        # ----------------------------------------------------

        for client_id in participating_ids:

            row = round_schedule[
                round_schedule["client_id"]
                == client_id
            ].iloc[0]

            client_seed = (
                seed
                + round_number * 1000
                + client_id
            )

            set_seed(
                client_seed
            )

            client_df = scaled_clients[
                client_id
            ]

            noise_multiplier = float(
                row[
                    "sensor_noise_multiplier"
                ]
            )

            stale_requested = bool(
                row["stale_update"]
            )

            # -----------------------------------------------
            # Apply sensor noise to this round's local data.
            # -----------------------------------------------

            if noise_multiplier > 0:

                actual_noisy_clients += 1

                client_df = apply_sensor_noise(
                    client_df=client_df,
                    feature_columns=feature_columns,
                    noise_multiplier=noise_multiplier,
                    seed=(
                        seed
                        + round_number * 10000
                        + client_id
                    ),
                )

            # -----------------------------------------------
            # Train current local model.
            # -----------------------------------------------

            (
                current_state,
                local_loss,
                sample_count,
            ) = train_local_model(
                global_state=global_state,
                client_df=client_df,
                device=DEVICE,
                input_size=len(
                    feature_columns
                ),
                local_epochs=local_epochs,
                learning_rate=learning_rate,
                batch_size=batch_size,
            )

            # -----------------------------------------------
            # Save current update as client's newest state.
            # -----------------------------------------------

            previous_state = (
                previous_client_states.get(
                    client_id
                )
            )

            previous_client_states[
                client_id
            ] = copy_state_dict(
                current_state
            )

            # -----------------------------------------------
            # Stale update simulation.
            #
            # If requested and a previous update exists,
            # submit the previous update instead of current.
            # -----------------------------------------------

            submitted_state = current_state
            stale_used = False

            if (
                stale_requested
                and previous_state is not None
            ):

                submitted_state = (
                    copy_state_dict(
                        previous_state
                    )
                )

                stale_used = True
                actual_stale_clients += 1

            local_states.append(
                submitted_state
            )

            local_counts.append(
                sample_count
            )

            local_losses.append(
                local_loss
            )

            status = []

            if noise_multiplier > 0:
                status.append(
                    f"noise={noise_multiplier:.2f}"
                )

            if stale_used:
                status.append(
                    "STALE_UPDATE"
                )

            if not status:
                status.append(
                    "normal"
                )

            print(
                f"Client {client_id:02d}: "
                f"samples={sample_count:3d} "
                f"loss={local_loss:.6f} "
                f"[{', '.join(status)}]"
            )

        # ----------------------------------------------------
        # Standard FedAvg.
        #
        # IMPORTANT:
        # No reliability score is used here.
        # ----------------------------------------------------

        aggregation_start = (
            time.perf_counter()
        )

        global_state = fedavg(
            local_states,
            local_counts,
        )

        aggregation_time = (
            time.perf_counter()
            - aggregation_start
        )

        model.load_state_dict(
            global_state
        )

        # ----------------------------------------------------
        # Evaluation
        # ----------------------------------------------------

        metrics = evaluate_model(
            model,
            scaled_test,
            feature_columns,
        )

        round_time = (
            time.perf_counter()
            - round_start
        )

        participating = len(
            participating_ids
        )

        failed = (
            N_CLIENTS
            - participating
        )

        # Communication is based on participating clients only.
        upload_bytes = (
            participating
            * model_bytes
        )

        download_bytes = (
            participating
            * model_bytes
        )

        total_communication = (
            upload_bytes
            + download_bytes
        )

        mean_reliability = float(
            round_schedule[
                round_schedule["available"]
            ]["reliability_score"]
            .mean()
        )

        history.append(
            {
                "scenario": scenario,
                "round": round_number,
                "available_clients": participating,
                "failed_clients": failed,
                "noisy_clients": actual_noisy_clients,
                "stale_clients": actual_stale_clients,
                "mean_reliability_available_clients": mean_reliability,
                "mean_local_loss": float(
                    np.mean(
                        local_losses
                    )
                ),
                "global_test_loss": metrics[
                    "global_test_loss"
                ],
                "accuracy": metrics[
                    "accuracy"
                ],
                "precision": metrics[
                    "precision"
                ],
                "recall": metrics[
                    "recall"
                ],
                "f1": metrics[
                    "f1"
                ],
                "roc_auc": metrics[
                    "roc_auc"
                ],
                "model_parameters": parameter_count(
                    global_state
                ),
                "model_size_bytes": model_bytes,
                "upload_bytes": upload_bytes,
                "download_bytes": download_bytes,
                "total_communication_bytes": total_communication,
                "aggregation_time_seconds": aggregation_time,
                "round_time_seconds": round_time,
            }
        )

        print(
            f"Global test loss : "
            f"{metrics['global_test_loss']:.6f}"
        )

        print(
            f"Accuracy         : "
            f"{metrics['accuracy']:.6f}"
        )

        print(
            f"Precision        : "
            f"{metrics['precision']:.6f}"
        )

        print(
            f"Recall           : "
            f"{metrics['recall']:.6f}"
        )

        print(
            f"F1               : "
            f"{metrics['f1']:.6f}"
        )

        print(
            f"ROC-AUC          : "
            f"{metrics['roc_auc']:.6f}"
        )

        print(
            f"Communication    : "
            f"{total_communication / (1024 ** 2):.4f} MiB"
        )

    return pd.DataFrame(
        history
    )


