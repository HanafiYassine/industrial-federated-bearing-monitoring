"""
run_fedavg_reliability.py

Run standard FedAvg under industrial client-reliability scenarios.

Scenarios consumed from:
    ../results/federated/dataset2_reliability/<scenario>/

Supported:
    clean
    sensor_noise
    stale_updates
    persistent_failure
    mixed

The model, optimizer, local training procedure, client partitions and
global test set remain the same as the validated FedAvg baseline.

This script changes ONLY the client-reliability condition.

Reliability effects:
    sensor_noise:
        Perturb affected client's input features during local training.

    stale_updates:
        Affected clients submit their previous-round local update when
        the schedule marks the client as stale. On the first round,
        no previous update exists, so the current update is used.

    persistent_failure:
        Affected clients are unavailable and do not participate.

    mixed:
        Applies any combination encoded in the schedule.

Important:
    The reliability_score generated by the simulator is logged but is
    NOT used by standard FedAvg. That score is reserved for the later
    proposed reliability-aware optimization.

Usage:
    python run_fedavg_reliability.py --scenario sensor_noise
    python run_fedavg_reliability.py --scenario stale_updates
    python run_fedavg_reliability.py --scenario persistent_failure
    python run_fedavg_reliability.py --scenario mixed

Optional:
    --rounds 15
    --local-epochs 1
    --batch-size 512
    --learning-rate 0.001
    --seed 42
"""

